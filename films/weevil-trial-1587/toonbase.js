const hatOn = (p, o, hp, H, cx, hc, light, seed, facing) => {
  const W = 2 * H.a, HH = 2 * H.b, u = W / 100, crown = hc - H.b, ow = 0.85 * 5 * u;
  const a = H.rot + rad(4 * (rnd(seed, 20) - 0.5));
  const R = (pts) => rotPts(pts, a, cx, hc);
  const sag = (yb, wb) => {
    const base = [];
    for (let i = 0; i <= 12; i++) { const t = i / 12; base.push([cx + wb * (2 * t - 1), yb + 3 * u * (1 - (2 * t - 1) ** 2)]); }
    return base;
  };
  if (o.hat === "cap" || o.hat === "hair") {
    const cut = crown + (o.hat === "cap" ? 0.3 : 0.42) * HH;
    const keep = (x, y) => y < cut;
    const n = hp.length, startIdx = Math.max(0, hp.findIndex(([x, y], i) => keep(x, y) && !keep(hp[(i + n - 1) % n][0], hp[(i + n - 1) % n][1])));
    const arc = [...hp.slice(startIdx), ...hp.slice(0, startIdx)].filter(([x, y]) => keep(x, y))
      .map(([x, y]) => [cx + (x - cx) * 1.03, hc + (y - hc) * 1.03]);
    if (arc.length < 3) return;
    if (o.hat === "hair") {
      const [x0, y0] = arc[arc.length - 1], [x1, y1] = arc[0];
      for (let i = 1; i < 6; i++) arc.push([x0 + ((x1 - x0) * i) / 6, y0 + ((y1 - y0) * i) / 6 + (i % 2 ? 4 * u : 0)]);
    }
    const col = o.hat === "cap" ? o.cap : o.hair;
    p.shadedFill(arc, col, mul(col, SH_FELT), light, H.a, 0.35);
    p.poly(arc, null, ow);
    if (o.hat === "hair") {
      const s = facing || 1;
      p.stroke([[cx + s * 10 * u, cut - 30 * u], [cx + s * 2 * u, cut - 12 * u]], 1.2 * u);
    }
    if (o.hat === "cap") {
      const deg = (a * 180) / Math.PI;
      const s = facing || (rnd(seed, 21) < 0.5 ? -1 : 1), [px, py] = R([[cx + s * 4 * u, cut + 1.5 * u]])[0];
      p.ell(px, py, 32 * u, 0.06 * HH, shade(col, 0.8), ow, 0, 180, deg);
    }
  } else if (o.hat === "lawyer" || o.hat === "miter") {
    // 16th-century French square lawyer toque (`barrette`) or bishop's velvet miter cap
    const yb = crown + 0.24 * HH, col = o.hat === "miter" ? "#7a2c38" : "#25212c";
    if (o.hat === "miter") {
      const peak = R([...sag(yb, 0.36 * W).reverse(), [cx - 0.38 * W, yb - 0.52 * HH], [cx, yb - 0.96 * HH], [cx + 0.38 * W, yb - 0.52 * HH]]);
      p.shadedFill(peak, col, mul(col, SH_FELT), light, 0.4 * W, 0.4);
      p.clip(peak, () => p.band(R([[cx - 0.4 * W, yb - 0.09 * HH], [cx + 0.4 * W, yb - 0.09 * HH]]), "#e2b955", 0.13 * HH, 1.4 * u));
      p.poly(peak, null, ow);
      const [cx0, cy0] = R([[cx, yb - 0.48 * HH]])[0];
      p.stroke(R([[cx - 8 * u, cy0], [cx + 8 * u, cy0]]), 3.5 * u, "#e2b955");
      p.stroke(R([[cx, cy0 - 12 * u], [cx, cy0 + 12 * u]]), 3.5 * u, "#e2b955");
    } else {
      // Lawyer's flat velvet bonnet + curly temple wisps
      const ht = 0.42 * HH, wb = 0.38 * W, wt = 0.48 * W;
      const body = R([...sag(yb, wb).reverse(), [cx - wt, yb - ht], [cx + wt, yb - ht]]);
      p.shadedFill(body, col, mul(col, SH_FELT), light, wt, 0.4);
      p.poly(body, null, ow);
      const [cxL, cyL] = R([[cx - 0.42 * W, yb + 24 * u]])[0];
      const [cxR, cyR] = R([[cx + 0.42 * W, yb + 24 * u]])[0];
      p.ell(cxL, cyL, 12 * u, 20 * u, "#dad4c8", ow * 0.7);
      p.ell(cxR, cyR, 12 * u, 20 * u, "#dad4c8", ow * 0.7);
    }
  } else if (o.hat === "straw") {
    const yb = crown + 0.25 * HH, col = "#d9b45a";
    const crownPts = R([...sag(yb, 0.34 * W).reverse(), [cx - 0.28 * W, yb - 0.42 * HH], [cx + 0.28 * W, yb - 0.42 * HH]]);
    p.shadedFill(crownPts, col, mul(col, SH_CLOTH), light, 0.35 * W, 0.4);
    p.clip(crownPts, () => p.band(R([[cx - 0.35 * W, yb - 0.08 * HH], [cx + 0.35 * W, yb - 0.08 * HH]]), "#8c3b4a", 0.1 * HH, 0.8 * u));
    p.poly(crownPts, null, ow);
    const [bx, by] = R([[cx, yb + 2 * u]])[0];
    p.ell(bx, by, 0.54 * W, 0.075 * HH, shade(col, 0.92), ow, 0, 360, (a * 180) / Math.PI);
  } else if (o.hat === "bonnet") {
    const [bx, by] = R([[cx, crown + 0.16 * HH]])[0];
    p.arc(bx, by, 0.5 * W, 0.2 * HH, 200, 340, 7 * u, BONNET_BRIM);
    p.arc(bx, by, 0.5 * W + 3.5 * u, 0.2 * HH + 3.5 * u, 200, 340, 1.2 * u);
    const cy = hc + H.b * 0.98;
    p.stroke([[cx - 14 * u, cy - 4 * u], [cx, cy + 2 * u], [cx + 14 * u, cy - 4 * u]], 2 * u, BONNET_BRIM);
  }
};

export const BUILD = {
  adult: { a: 118, torso: 1.1, legs: 1.4, tw: 0.8 },
  stout: { a: 118, torso: 1.15, legs: 1.32, tw: 0.92 },
};

const footStroke = (p, a, b, w, col) => {
  if (col !== INK) p.stroke([a, b], w + 3, INK);
  p.stroke([a, b], w, col);
};

export const bodyFront = (p, o, opts) => {
  const { phase = 0, expr = "neutral", mode = "stand", look = 0, blink = false, lift = 60, tilt = 0, headTilt = 0, wave,
    light = DEF_LIGHT, facing = 0, seed = 1, talk = 0 } = opts;
  const Bd = BUILD[o.build ?? "adult"], skin = o.skin ?? SKIN, two = Math.PI * 2, lid = lidOf(blink);
  const H = headBlob(seed, Bd.a, facing), W = 2 * H.a, HH = 2 * H.b, u = W / 100;
  const tall = (1 + Bd.torso + Bd.legs) * HH, sole = 975;
  const bob = mode === "march" ? 0.025 * tall * Math.cos(2 * two * phase) : mode === "stroll" ? 0.015 * tall * Math.cos(2 * two * phase) : 0;
  const torsoBot = mode === "sit" || mode === "kneel" ? sole - 0.22 * HH : sole - Bd.legs * HH + bob;
  const chin = torsoBot - Bd.torso * HH, hc = chin - H.b, hipY = torsoBot - 0.12 * HH;
  const thick = thickAngle(light), ow = 5 * u;
  const legCol = mix(o.pants, INK, 0.55), armCol = mix(o.jacket, INK, 0.5), footCol = o.boots;
  const legW = 5.8 * u, footW = 7.5 * u;

  p.rot = null;
  if (mode === "sit" || mode === "kneel") {
    for (const side of [-1, 1]) {
      const h = [300 + side * 15 * u, hipY], k = [300 + side * 34 * u, hipY + 0.18 * HH], f = [300 + side * 42 * u, sole - 8 * u];
      p.stroke(curve(h, k, f), legW, legCol);
      footStroke(p, [f[0] - side * 2 * u, f[1]], [f[0] + side * 12 * u, f[1] - 4 * u], footW, footCol);
    }
  } else if (o.dress) {
    for (const side of [-1, 1]) {
      const fx = 300 + side * 12 * u, fy = sole - 4 * u;
      p.stroke([[fx, sole - 0.4 * HH], [fx + side * u, fy]], legW, legCol);
      footStroke(p, [fx - side * 3 * u, fy], [fx + side * 12 * u, fy + u], footW, footCol);
    }
  } else {
    const L = mode === "march" ? lift * 1.25 : mode === "stroll" ? lift * 0.55 : 0;
    for (const [side, ph] of [[-1, 0], [1, 0.5]]) {
      const up = Math.max(0, Math.sin(two * (phase + ph))) * L;
      const hx = 300 + side * 15 * u, fx = 300 + side * 22 * u, fy = sole - 4 * u - up;
      const k = [(hx + fx) / 2 + side * (1.5 * u + up * 0.16), (hipY + fy) / 2 - up * 0.08];
      p.stroke(curve([hx, hipY], k, [fx, fy]), legW, legCol);
      footStroke(p, [fx - side * 3 * u, fy], [fx + side * 13 * u, fy + 0.5 * u], footW, footCol);
    }
  }

  const sway = mode === "march" ? 1.6 * Math.sin(two * phase) : mode === "stroll" ? 1.0 * Math.sin(two * phase) : 0;
  const A = tilt + sway;
  p.rot = A ? [rad(A), 300, hipY] : null;
  const dress = !!o.dress && mode !== "sit" && mode !== "kneel";
  const T = {
    a: ((Bd.tw / 2) * W) / 1.06, b: 0.5 * (torsoBot - (chin - 0.25 * HH)),
    nTop: 2.2, nBot: 2.6, egg: o.build === "stout" ? 0.17 : 0.12,
    asym: 0.04 * facing, rot: 0, noise: 0.006, seed: seed + 7,
  };
  const tcx = 300 + 3 * u * facing, tcy = torsoBot - T.b, tp = blobPts(tcx, tcy, T);
  const sh = (side) => [tcx + side * 0.85 * T.a, chin + 0.12 * HH];
  const hang = (side, fwd) => {
    const S = sh(side), ex = tcx + side * (1.12 * T.a + 4 * u);
    const hx = ex + side * 3 * u - side * 6 * u * Math.max(0, fwd) + side * 4 * u * Math.max(0, -fwd);
    return [S, [ex, S[1] + 0.48 * HH], [hx, chin + 1.04 * HH - Math.abs(fwd) * 9 * u]];
  };
  const sw = mode === "march" || mode === "stroll" ? Math.sin(two * phase) : 0;
  const arms = [];
  if (mode === "sit" || mode === "kneel") {
    for (const side of [-1, 1]) arms.push({ pts: [sh(side), [tcx + side * (1.1 * T.a + 6 * u), sh(side)[1] + 0.4 * HH], [tcx + side * (1.2 * T.a + 10 * u), torsoBot + 0.04 * HH]], front: false });
  } else {
    arms.push({ pts: hang(-1, -sw), front: false });
    if (wave !== undefined) {
      const S = sh(1);
      arms.push({ pts: [S, [tcx + 1.1 * T.a + 10 * u + 3 * u * wave, S[1] - 0.22 * HH], [tcx + 1.18 * T.a + 16 * u + 12 * u * wave, S[1] - 0.6 * HH]], front: false });
    } else {
      arms.push({ pts: hang(1, sw), front: false });
    }
  }
  const drawArm = (a) => { p.stroke(curve(a.pts[0], a.pts[1], a.pts[2]), 5.2 * u, armCol); p.dot(a.pts[2][0], a.pts[2][1], 5.5 * u); };
  for (const a of arms) if (!a.front) drawArm(a);

  if (dress) {
    const D = { a: 0.5 * W * 0.98, b: 0.5 * ((sole - 0.35 * HH) - (chin - 0.2 * HH)), nTop: 2.0, nBot: 3.0, egg: 0.35, asym: 0.03 * facing, rot: 0, noise: 0.006, seed: seed + 9 };
    const dp = blobPts(300, sole - 0.35 * HH - D.b, D);
    p.gradFill(dp, o.dress, mul(o.dress, SH_CLOTH), light);
    p.inkRing(dp, ow, thick);
    const Sw = { a: 0.37 * W, b: 0.3 * HH, nTop: 2.2, nBot: 2.4, egg: 0.1, asym: 0, rot: 0, noise: 0.006, seed: seed + 8 };
    const sp = blobPts(300, chin + 0.12 * HH, Sw);
    p.gradFill(sp, o.jacket, mul(o.jacket, SH_CLOTH), light);
    if (o.bib) {
      // Crisp white lawyer collar tabs (`rabat`)
      p.poly([[tcx - 10 * u, chin + 2 * u], [tcx - 2 * u, chin + 2 * u], [tcx - 4 * u, chin + 28 * u], [tcx - 13 * u, chin + 26 * u]], "#f7f3ea", 2.2 * u);
      p.poly([[tcx + 2 * u, chin + 2 * u], [tcx + 10 * u, chin + 2 * u], [tcx + 13 * u, chin + 26 * u], [tcx + 4 * u, chin + 28 * u]], "#f7f3ea", 2.2 * u);
    }
    p.inkRing(sp, ow * 0.9, thick);
  } else {
    p.gradFill(tp, o.jacket, mul(o.jacket, SH_CLOTH), light);
    p.clip(tp, () => {
      if (o.apron) {
        p.poly([[tcx - 0.65 * T.a, chin + 0.22 * HH], [tcx + 0.65 * T.a, chin + 0.22 * HH], [tcx + 0.8 * T.a, torsoBot + 0.1 * HH], [tcx - 0.8 * T.a, torsoBot + 0.1 * HH]], o.apron, 2.5 * u);
      }
      for (let i = 0; i < 4; i++) {
        const y = chin + 0.14 * HH + i * 0.19 * HH;
        p.dot(tcx + 2 * u * facing, y, 2.2 * u + 0.8 * u, INK);
        p.dot(tcx + 2 * u * facing, y, 2.2 * u, o.buttons ?? shade(o.jacket, 0.72));
      }
    });
    p.inkRing(tp, ow, thick);
  }

  const Ah = A + headTilt, [cpx, cpy] = rotAbout([300, chin], rad(A), [300, hipY]);
  p.rot = Ah ? [rad(Ah), 300, chin, cpx - 300, cpy - chin] : null;
  hatBehind(p, o, H, 300, hc, light, thick, ow);
  const hp = blobPts(300, hc, H);
  p.shadedFill(hp, skin, mul(skin, SH_SKIN), light, H.a);
  p.inkRing(hp, ow, thick);
  hatOn(p, o, hp, H, 300, hc, light, seed, facing);
  const brim = !!o.hat && o.hat !== "hair" && o.hat !== "bonnet" && o.hat !== "cap";
  faceFront(p, 300, hc, W, expr, facing, look, lid, brim, skin, o.moustache, o.build === "stout", talk);
  p.rot = null;
};

export const fxPuff = (p, t) => {
  for (let i = 0; i < 5; i++) {
    const a = rad(160 + i * 55), d = 40 + 70 * t, r = (34 + 20 * (i % 2)) * (1 - 0.6 * t);
    p.ell(150 + d * Math.cos(a), 180 + d * 0.45 * Math.sin(a), r, r * 0.8, `rgba(238,225,205,${(1 - t).toFixed(3)})`, 0);
  }
};

export const fxShadow = (p, col) => {
  const g = p.g;
  g.fillStyle = WHITE; g.fillRect(0, 0, 128, 256);
  g.save(); g.filter = "blur(9px)";
  const lg = g.createLinearGradient(0, 205, 0, 22);
  lg.addColorStop(0, mix(col, WHITE, 0.08)); lg.addColorStop(0.55, mix(col, WHITE, 0.3)); lg.addColorStop(1, mix(col, WHITE, 0.85));
  g.fillStyle = lg;
  g.beginPath(); g.moveTo(40, 205); g.bezierCurveTo(36, 120, 46, 50, 64, 30); g.bezierCurveTo(82, 50, 92, 120, 88, 205); g.closePath(); g.fill();
  g.fillStyle = col; g.beginPath(); g.ellipse(64, 205, 30, 17, 0, 0, Math.PI * 2); g.fill();
  g.restore();
};

